function applyFrame(svg, f) {
  const set = (sel, attr, v) => { const e = svg.querySelector(sel); if (e) e.setAttribute(attr, v); };
  const pt = p => p[0].toFixed(1) + ',' + p[1].toFixed(1);
  set('.j-torso', 'x1', f.p[0]); set('.j-torso', 'y1', f.p[1]);
  set('.j-torso', 'x2', f.n[0]); set('.j-torso', 'y2', f.n[1]);
  set('.j-head', 'cx', f.h[0]); set('.j-head', 'cy', f.h[1]);
  set('.j-arm', 'points', pt(f.n) + ' ' + pt(f.e) + ' ' + pt(f.w));
  set('.j-arm2', 'points', pt(f.n) + ' ' + pt(f.e2) + ' ' + pt(f.w2));
  set('.j-leg', 'points', pt(f.p) + ' ' + pt(f.k) + ' ' + pt(f.f));
  set('.j-leg2', 'points', pt(f.p) + ' ' + pt(f.k2) + ' ' + pt(f.f2));
}

function tick(ts) {
  const dt = lastTs ? (ts - lastTs) : 0;
  lastTs = ts;
  instances.forEach(inst => {
    if (!inst.playing) return;
    inst.t += dt / inst.segMs;
    while (inst.t >= inst.segN) inst.t -= inst.segN;
    const i = Math.floor(inst.t);
    const raw = inst.t - i;
    const t = ease(raw);
    const A = inst.frames[i], B = inst.frames[(i + 1) % inst.frames.length];
    const cur = {};
    P_ORDER.forEach(k => { cur[k] = [lerp(A[k][0], B[k][0], t), lerp(A[k][1], B[k][1], t)]; });
    applyFrame(inst.svg, cur);
  });
  rafId = requestAnimationFrame(tick);
}

function mountPose(el, key) {
  const pose = POSES[key];
  if (!pose || !el) return null;
  if (pose.img) {
    el.innerHTML = '<img class="pose-img" src="' + pose.img + '" alt="' + pose.label + '">';
    return null;
  }
  buildSVG(el, pose);
  const svg = el.querySelector('svg');
  const frames = pose.f.map(normFrame);
  const single = frames.length === 1;
  const inst = {
    svg, frames, t: 0,
    segN: single ? 1 : frames.length,
    segMs: 620, playing: !single
  };
  applyFrame(svg, frames[0]);
  instances.push(inst);
  if (!rafId) rafId = requestAnimationFrame(tick);
  el.onclick = (e) => {
    e.stopPropagation();
    if (single) return;
    inst.playing = !inst.playing;
    el.classList.toggle('paused', !inst.playing);
  };
  return inst;
}

function clearPoses() { instances.length = 0; }

/* 清理已被移除的 DOM 对应的实例，避免重复渲染时泄漏 */
function pruneInstances() {
  for (let i = instances.length - 1; i >= 0; i--) {
    if (!document.body.contains(instances[i].svg)) instances.splice(i, 1);
  }
}
