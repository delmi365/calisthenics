function findPose(name) {
  for (const [kw, key] of POSE_MATCH) {
    if (name.indexOf(kw) >= 0 && POSES[key]) return key;
  }
  return null;
}

/* ---------- 渲染 ---------- */
function normFrame(fr) {
  const o = {};
  ['h', 'n', 'e', 'w', 'p', 'k', 'f'].forEach((k, i) => { o[k] = fr[i]; });
  o.e2 = fr[7] || [o.e[0] + 4, o.e[1] - 2];
  o.w2 = fr[8] || [o.w[0] + 4, o.w[1] - 2];
  o.k2 = fr[9] || [o.k[0] + 5, o.k[1] - 2];
  o.f2 = fr[10] || [o.f[0] + 5, o.f[1] - 2];
  return o;
}

