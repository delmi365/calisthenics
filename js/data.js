/* ---------- 计划查询 ---------- */
function getDayInfo(dayNumber) {
  const week = Math.ceil(dayNumber / 7);
  const wd = ((dayNumber - 1) % 7) + 1; // 1=周一 ... 7=周日
  const phaseIndex = dayNumber <= 30 ? 0 : (dayNumber <= 60 ? 1 : 2);
  const isDeloadWeek = [4, 8, 12].includes(week);
  const base = (wd === 6 && isDeloadWeek) ? DELOAD : DAYS[wd];
  return { week, wd, weekday: WEEKDAY[wd - 1], phaseIndex, phase: PHASES[phaseIndex], day: base, isDeloadWeek };
}

/* 组数：减量周整周下调 1 组（HIIT 少 1 轮），自测日为 1 组 */
function getSets(info) {
  if (info.day.test) return 1;
  const cut = info.isDeloadWeek ? 1 : 0;
  if (info.day.hiit) return Math.max(2, info.phase.cardio.rounds - cut);
  return Math.max(2, info.phase.sets - cut);
}

function getExerciseList(dayNumber, gender) {
  const info = getDayInfo(dayNumber);
  const list = info.day[gender] || info.day.male || [];
  const sets = getSets(info);
  return list.map((ex, i) => ({
    idx: i,
    n: ex.n, m: ex.m, cue: ex.cue, down: ex.down, up: ex.up,
    reps: info.day.test ? ex.r[0] : ex.r[info.phaseIndex],
    sets: sets
  }));
}
