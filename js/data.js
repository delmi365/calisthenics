/* ---------- 饮食计算 ---------- */
function calcBMR(gender, weight, height, age) {
  // Mifflin-St Jeor
  const base = 10 * weight + 6.25 * height - 5 * age;
  return Math.round(gender === 'male' ? base + 5 : base - 161);
}

const ACTIVITY = 1.55; // 每周 6 天训练

function calcDiet(gender, goal, weight, height, age) {
  const bmr = calcBMR(gender, weight, height, age);
  const tdee = Math.round(bmr * ACTIVITY);
  const isMale = gender === 'male';

  let target, proteinPerKg, fatPerKg, note;
  if (goal === 'fatloss') {
    const gap = isMale ? 500 : 350;
    target = Math.max(tdee - gap, isMale ? 1500 : 1200); // 安全下限
    proteinPerKg = isMale ? 2.0 : 1.8;
    fatPerKg = isMale ? 0.8 : 0.9;
    note = isMale
      ? '缺口 500 kcal，每周预期减重 0.5-0.8 kg。低于体重 1%/周 说明掉太快，需加回 100-150 kcal。'
      : '缺口 350 kcal。女性缺口过大易导致月经紊乱、掉发与反弹，切忌低于 1200 kcal。';
  } else if (goal === 'muscle') {
    const surplus = isMale ? 350 : 250;
    target = tdee + surplus;
    proteinPerKg = isMale ? 1.8 : 1.6;
    fatPerKg = 1.0;
    note = isMale
      ? '盈余 350 kcal，预期每月增重 1-1.5 kg，其中约一半是肌肉。'
      : '盈余 250 kcal。女性增肌速度约为男性一半，盈余过大只会转化为脂肪。';
  } else {
    target = tdee;
    proteinPerKg = isMale ? 1.7 : 1.6;
    fatPerKg = 0.9;
    note = '热量维持，通过提高蛋白质占比与训练量改变身体成分（"重组"）。';
  }

  const protein = Math.round(weight * proteinPerKg);
  const fat = Math.round(weight * fatPerKg);
  const carb = Math.max(Math.round((target - protein * 4 - fat * 9) / 4), 50);
  const water = isMale ? 3.5 : 2.7;
  const fiber = isMale ? 30 : 25;

  return { bmr, tdee, target, protein, fat, carb, water, fiber, note, isMale };
}

